'use strict';
// Markdown из ответа агента → разметка Telegram.
//
// Агенты пишут markdown всегда: `**жирным**` выделен вывод, обратными кавычками — путь к
// файлу, тройными — кусок кода. В чат это уезжало дословно, со звёздочками, и ответ на
// телефоне читался как черновик. Здесь он превращается в то, что телега умеет рисовать.
//
// ПОЧЕМУ HTML, А НЕ MARKDOWN. У Telegram два формата, и MarkdownV2 в нашем случае —
// ловушка: в нём экранировать надо восемнадцать символов (`_*[]()~>#+-=|{}.!`), и любой
// пропущенный означает не «абзац без курсива», а отказ всего сообщения с 400. То есть ответ
// агента не приходит вовсе — ровно там, где он нужнее всего, на телефоне. У HTML же особых
// символов три (`&<>`), тэги закрываются явно, и что получится, видно глазами.
//
// ЧЕГО ЗДЕСЬ НЕТ. Телега рисует не всё: заголовки, таблицы и списки ей неизвестны. Заголовок
// поэтому становится жирной строкой, маркер списка — точкой «•», а таблица остаётся текстом.
// Придумывать за телегу больше, чем она умеет, — это и есть тот случай, когда «адаптер»
// начинает врать.
//
// НАДЁЖНОСТЬ. Тэги ставятся только парами и только вокруг того, что нашлось целиком: одинокая
// звёздочка или незакрытая тройная кавычка остаётся текстом, а не превращается в сломанную
// разметку. Куски кода вынимаются ПЕРВЫМИ и не разбираются вообще — внутри них `*` это
// умножение, а `<` это меньше. И на случай, если разметка всё-таки не понравится телеге,
// у моста есть второй заход без неё (см. tgSend): текст доходит всегда.
//
// Отдельный модуль со своими тестами, а не десяток замен внутри main: сломать здесь легко и
// незаметно — ошибка видна не в коде, а в чужом сообщении на телефоне.

// Экранирование для parse_mode: 'HTML'. Ровно три символа — больше телега не выделяет.
function escapeHtml(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

// Язык у ``` бывает любым словом («ts», «c++», «objective-c»), но подпихивать его в class
// стоит только если это правда слово: остальное молча роняет разбор на стороне телеги.
const LANG_RE = /^[a-z0-9+#._-]{1,20}$/i;
// Ссылки берём только те, по которым можно ходить. `[текст](путь/к/файлу)` — не ссылка, и
// делать из неё <a href> значит показать на телефоне то, что не откроется.
const URL_RE = /^(?:https?:\/\/|tg:\/\/|mailto:)[^\s<>"]+$/i;

// Метка вынутого куска кода. Нулевой байт в тексте от агента не встречается, а если он вдруг
// там окажется — вырезаем его в самом начале: иначе метку можно было бы подделать текстом
// сообщения и вклинить свой тэг.
const MARK = '\u0000';

function toHtml(src) {
  const kept = [];
  const keep = (html) => {
    kept.push(html);
    return `${MARK}${kept.length - 1}${MARK}`;
  };

  let t = String(src == null ? '' : src).replace(/\u0000/g, '');

  // 1. Куски кода — первыми и целиком, вместе с содержимым: внутри них разметки нет, там
  //    текст как есть. Незакрытая тройная кавычка не совпадёт и останется текстом.
  t = t.replace(/```([^\n`]*)\n?([\s\S]*?)```/g, (_m, lang, body) => {
    const l = String(lang || '').trim();
    const open = LANG_RE.test(l) ? `<pre><code class="language-${l.toLowerCase()}">` : '<pre>';
    const close = LANG_RE.test(l) ? '</code></pre>' : '</pre>';
    return keep(open + escapeHtml(String(body).replace(/\n$/, '')) + close);
  });
  // 2. Однострочный код. Пара обратных кавычек в пределах строки — иначе это просто кавычка.
  t = t.replace(/`([^`\n]+)`/g, (_m, code) => keep('<code>' + escapeHtml(code) + '</code>'));

  // 3. Всё остальное — обычный текст, и с этого момента он экранирован. Дальше мы ДОБАВЛЯЕМ
  //    тэги, поэтому ни один `<` из ответа агента уже не может ими притвориться.
  t = escapeHtml(t);

  // 4. Ссылки. Подпись экранирована выше, адрес — тоже (&amp; в href это верно).
  t = t.replace(/\[([^\]\n]+)\]\(([^()\s]+)\)/g, (m, label, url) => (
    URL_RE.test(url) ? `<a href="${url}">${label}</a>` : m
  ));

  // 5. Заголовок → жирная строка: своих заголовков у телеги нет.
  t = t.replace(/^[ \t]{0,3}#{1,6}[ \t]+(.+?)[ \t]*#*$/gm, '<b>$1</b>');

  // 6. Маркер списка → точка. Только с пробелом после маркера: «---» это линейка, а
  //    «**жирное**» в начале строки — не список.
  t = t.replace(/^([ \t]*)[-*+][ \t]+(?=\S)/gm, '$1• ');

  // 7. Жирное — до курсива, иначе `**x**` разберётся как курсив вокруг `*x*`.
  t = t.replace(/(\*\*|__)(?=\S)([\s\S]*?\S)\1/g, '<b>$2</b>');
  // 8. Зачёркнутое.
  t = t.replace(/~~(?=\S)([\s\S]*?\S)~~/g, '<s>$1</s>');
  // 9. Курсив. В пределах одной строки и не внутри слова: `snake_case_имя` и `2 * 3 * 4`
  //    курсивом быть не должны, а с этими границами и не станут.
  // Границы — по буквам ЛЮБОГО алфавита, а не по \w: \w в JS это только латиница, и без
  // \p{L} «файл_с_подчёркиваниями» уезжал в чат с курсивом посреди слова.
  t = t.replace(/(?<![\p{L}\p{N}*])\*(?=\S)([^*\n]+?)\*(?![\p{L}\p{N}*])/gu, '<i>$1</i>');
  t = t.replace(/(?<![\p{L}\p{N}_])_(?=\S)([^_\n]+?)_(?![\p{L}\p{N}_])/gu, '<i>$1</i>');

  // 10. Вернуть куски кода на места.
  return t.replace(new RegExp(MARK + '(\\d+)' + MARK, 'g'), (_m, n) => kept[Number(n)] || '');
}

module.exports = { toHtml, escapeHtml, MARK };
